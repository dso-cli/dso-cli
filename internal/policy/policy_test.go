package policy

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestGenerateCODEOWNERS(t *testing.T) {
	t.Parallel()
	out, err := GenerateCODEOWNERS(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out, "CODEOWNERS generated by DSO") {
		t.Fatal("missing header")
	}
	if !strings.Contains(out, ".github/workflows") {
		t.Fatal("expected GitHub workflows pattern")
	}
}

func TestGenerateOPAPolicy_containsPackage(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "Dockerfile"), []byte("FROM scratch\nUSER root\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	policy, err := GenerateOPAPolicy(dir)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(policy, "package dso.security") {
		t.Fatal("missing package declaration")
	}
	if !strings.Contains(policy, "deny_secrets") {
		t.Fatal("expected deny_secrets rules")
	}
}

func TestDetectFileType(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	sub := filepath.Join(dir, "k8s")
	if err := os.MkdirAll(sub, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(sub, "deploy.yaml"), []byte("apiVersion: v1\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if !detectFileType(dir, "*.yaml") {
		t.Fatal("expected yaml glob match")
	}
}
